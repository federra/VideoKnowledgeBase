import {fireEvent,render,screen,within} from '@testing-library/react';
import {beforeEach,expect,it} from 'vitest';
import {App} from '../src/app/App';
beforeEach(()=>{localStorage.clear();localStorage.setItem('cip-demo-v1-workspace','AI漫剧');window.location.hash='#0/1'});
it('闪念历史可浏览，拖入组合后仅显式保存才新增选题',async()=>{
 render(<App/>);await screen.findByRole('button',{name:'头脑风暴'});
 fireEvent.click(screen.getByRole('button',{name:'打开闪念胶囊'}));
 fireEvent.input(screen.getByRole('textbox',{name:'记录灵感，输入后自动保存'}),{target:{value:'影子先回家\n人却仍在地铁'}});
 fireEvent.click(screen.getByRole('button',{name:'新记录'}));
 fireEvent.input(screen.getByRole('textbox',{name:'记录灵感，输入后自动保存'}),{target:{value:'失忆反派知道所有秘密'}});
 const read=()=>JSON.parse(localStorage.getItem('cip-demo-v1')!);
 const count=read().topics.length,first=read().sparks[1].id;
 fireEvent.click(screen.getByRole('button',{name:'关闭'}));
 fireEvent.click(screen.getByRole('button',{name:'头脑风暴'}));
 const zone=screen.getByLabelText('头脑风暴交互区');
 fireEvent.drop(zone,{dataTransfer:{getData:(type:string)=>type==='application/x-cip-spark'?first:''}});
 fireEvent.click(screen.getByRole('button',{name:/失忆反派知道所有秘密/}));
 fireEvent.click(screen.getByRole('button',{name:'生成一个选题'}));
 expect(read().topics).toHaveLength(count);
 expect(screen.getByText('演示 · 未调用AI')).toBeTruthy();
 fireEvent.input(screen.getByRole('textbox',{name:'选题标题'}),{target:{value:'人工整理的新方向'}});
 fireEvent.click(screen.getByRole('button',{name:'保存为选题卡'}));
 expect(read().topics).toHaveLength(count+1);expect(read().topics[0].title).toBe('人工整理的新方向');
 expect(read().topics[0].ideaRefs).toHaveLength(2);
 expect(within(screen.getByRole('dialog')).getByText('来源闪念')).toBeTruthy();
});
it('修改生成方向会清除旧结果，重复添加不会重复计入',async()=>{
 render(<App/>);await screen.findByRole('button',{name:'头脑风暴'});
 fireEvent.click(screen.getByRole('button',{name:'打开闪念胶囊'}));
 fireEvent.input(screen.getByRole('textbox',{name:'记录灵感，输入后自动保存'}),{target:{value:'月亮失踪'}});
 fireEvent.click(screen.getByRole('button',{name:'关闭'}));fireEvent.click(screen.getByRole('button',{name:'头脑风暴'}));
 const add=screen.getByRole('button',{name:/月亮失踪/});fireEvent.click(add);fireEvent.click(document.querySelector('[data-action="brainstorm-add"]')!);
 fireEvent.click(screen.getByRole('button',{name:'生成一个选题'}));
 fireEvent.input(screen.getByRole('textbox',{name:'补充方向（选填）'}),{target:{value:'改为校园故事'}});
 expect(screen.queryByRole('button',{name:'保存为选题卡'})).toBeNull();
 fireEvent.click(screen.getByRole('button',{name:'关闭'}));fireEvent.click(screen.getByRole('button',{name:'头脑风暴'}));
 expect(screen.getByRole('textbox',{name:'补充方向（选填）'})).toHaveProperty('value','改为校园故事');
 expect(JSON.parse(localStorage.getItem('cip-demo-v1')!).brainstorms.AI漫剧.selectedIds).toHaveLength(1);
});
