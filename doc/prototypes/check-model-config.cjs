const assert = require('node:assert/strict');
const {boot} = require('./check-feedback.cjs');
(async()=>{
 const app=boot({},'#3/5');
 assert.equal(app.run('modules[3].tabs[5]'),'模型配置','新增独立Tab，保留旧路由');
 assert.match(app.nodes.get('page').innerHTML,/单文本模型源/);
 assert.match(app.nodes.get('page').innerHTML,/多模态模型源/);
 assert.equal(app.run('Object.keys(modelCapabilities).join(",")'),'text,vision');
 assert.ok(app.run('modelStages.some(s=>s[1]==="脚本分析")&&modelStages.some(s=>s[1]==="输出分析报告")&&modelStages.some(s=>s[1]==="视频分析")'));
 await app.run('action("new-model")');
 assert.match(app.nodes.get('dialog').innerHTML,/服务端密钥引用/);
 const model={id:'',name:'文本分析',provider:'OpenAI兼容',endpoint:'https://example.com/v1',model:'example-text',capability:'text',secretRef:'MODEL_KEY',timeout:'60',retries:'1',maxTokens:'4096'};
 app.submit({...model,endpoint:'https://example.com/v1?api_key=never-store'},'modelConfigForm');
 assert.equal(app.run('db.modelConnections.length'),0,'带查询参数的地址不能保存凭据');
 app.submit({...model,secretRef:'sk-not-a-reference'},'modelConfigForm');
 assert.equal(app.run('db.modelConnections.length'),0,'密钥原文不保存');
 app.submit(model,'modelConfigForm');
 assert.equal(app.run('db.modelConnections.length'),1);
 const id=app.run('db.modelConnections[0].id');
 app.submit({['binding:feedback']:id},'modelBindingsForm');
 assert.equal(app.run('db.modelBindings["故事短片"].feedback'),id,'环节只引用统一模型');
 const before=app.run('JSON.stringify(db.modelBindings)');
 app.submit({['binding:visual']:id},'modelBindingsForm');
 assert.equal(app.run('JSON.stringify(db.modelBindings)'),before,'不能把单文本模型源分给视频分析');
 app.submit({...model,id,model:'changed'},'modelConfigForm');
 assert.equal(app.run('db.modelConnections[0].version'),2);
 assert.equal(app.run('db.modelConnections[0].versions[0].model'),'example-text');
 app.submit({...model,name:'第二个文本源',model:'text-second'},'modelConfigForm');
 const second=app.run('db.modelConnections.at(-1).id');
 app.submit({...model,name:'视频源一',model:'video-one',capability:'vision'},'modelConfigForm');
 const video=app.run('db.modelConnections.at(-1).id');
 app.submit({...model,name:'视频源二',model:'video-two',capability:'vision'},'modelConfigForm');
 app.submit({['binding:feedback']:id,['binding:decompose']:second,['binding:report']:second,['binding:visual']:video},'modelBindingsForm');
 assert.equal(app.run('db.modelBindings["故事短片"].decompose'),second);
 assert.equal(app.run('db.modelBindings["故事短片"].report'),second);
 assert.equal(app.run('db.modelBindings["故事短片"].visual'),video);
 assert.equal(app.run('db.modelConnections.filter(x=>x.capability==="text").length'),2);
 assert.equal(app.run('db.modelConnections.filter(x=>x.capability==="vision").length'),2);
 app.submit({...model,id,capability:'vision'},'modelConfigForm');
 assert.equal(app.run('db.modelConnections[0].capability'),'text','已引用模型源不可直接换类');
 const saved=Object.fromEntries(app.storage);
 const restored=boot(saved,'#3/5');
 assert.equal(restored.run('db.modelConnections[0].model'),'changed','重新进入保留配置');
 await app.run('action("creator-manage")');
 assert.match(app.nodes.get('dialog').innerHTML,/个人主页链接/);
 const count=app.run('db.creators.length');
 app.submit({biz:'故事短片',name:'主页测试',profileUrl:'javascript:alert(1)'},'creatorForm');
 assert.equal(app.run('db.creators.length'),count,'非法链接不保存');
 app.submit({biz:'故事短片',name:'主页测试',profileUrl:'https://example.com/user/demo?from=share'},'creatorForm');
 assert.equal(app.run('db.creators.at(-1).profileUrl'),'https://example.com/user/demo?from=share');
 assert.match(app.nodes.get('dialog').innerHTML,/打开主页/);
 const legacyDb=JSON.parse(saved['content-ui-qa-v1']);
 legacyDb.modelConnections.push({...model,id:'OLD-ASR',capability:'speech',version:1});
 legacyDb.modelBindings['故事短片'].asr='OLD-ASR';
 const legacy=boot({'content-ui-qa-v1':JSON.stringify(legacyDb)},'#3/5');
 assert.equal(legacy.run('db.modelConnections.length'),4,'旧转写配置不混入两类来源');
 assert.equal(legacy.run('db.legacyModelConnections[0].id'),'OLD-ASR','旧草稿保留不丢失');
 assert.equal(legacy.run('db.legacyModelBindings[0].sourceId'),'OLD-ASR');
 await restored.run('action("reset")');
 assert.equal(restored.run('db.modelConnections.length'),0,'重置后模型页仍可正常使用');
 console.log('PASS: 独立模型Tab、配置持久化与版本、能力匹配、密钥引用、达人主页链接');
})().catch(error=>{console.error(error);process.exitCode=1;});
